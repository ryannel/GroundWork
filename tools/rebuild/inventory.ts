// Conservative inventories include candidates, never infer that a consumer has migrated.
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';

import { writeExplorerParity } from '@/../tools/explorer-parity';
import { isRecord } from '@/application/plan/ids';

import { identitySites } from './identity-inventory';
import { writeSnapshot } from './snapshots';

const OLD = [
  /WorkspaceModel|SystemModel|SystemGraph|\bWorkspace\b|\bToday\b|todayData|readToday|readWorkspace|systemModelOf|collectionsOf|onBase|legacyViewOf/u,
  /plan\.generated|domain\/workspace|infrastructure\/(?:today|workspace|plan|service-explorer|explorer)|application\/(?:workspace-model|plan\/derive)/u,
  /knowledge|scan-discovery|scan-interpretation|contracts\.yaml|handlers\.yaml|system\.yaml|story\.yaml|landscape\.yaml|base\.lock|talks_to|scans\/|explorer\//u,
  /\b(?:sys|svc|st|api|msg|sch|if|h):/u,
];
const IDS = [
  /\b(?:sys|svc|app|st|top|ext|lib|dom|api|sub|job|ui|msg|sch|if|h):/u,
  /\b(?:graph|sg|gql|scr|team|actor|area|flow|jny|uj|plan|prog|ev|con|term):/u,
  /(?:split|replace|replaceAll|startsWith|slice|indexOf|includes)\([^\n]*(?:['"`]#|['"`]:)/u,
  /idToToken|tokenToId|ID_PREFIXES|SYSTEM_COLLECTIONS|rootOf|typeOf\(/u,
];
const URLS = [
  /github\\?\.com|gitlab|bitbucket|(?:blob|tree|issues|pull)\//iu,
  /permalink|homeUrlOf|issueUrlOf|parseGitHostUrl|GITHUB_BLOB|\bGITHUB\b|sourceUrl|repoUrl|\$\{host\}/iu,
];
const QUALITY = new Set([
  'test/architecture.test.ts',
  'eslint.config.mjs',
  'knip.json',
  '.jscpd.json',
  'vitest.config.ts',
  'tools/design-drift.baseline.json',
  'tools/page-budget.ts',
]);

interface Hit {
  readonly line: number;
  readonly text: string;
}
interface Row {
  readonly file: string;
  readonly category: string;
  readonly status: 'adapter' | 'migrated' | 'deleted';
  readonly hits: readonly Hit[];
}

const categoryOf = (file: string): string => {
  if (QUALITY.has(file)) return 'quality configuration';
  if (file.startsWith('src/app/')) return 'route';
  if (file.startsWith('.agents/')) return 'skill';
  if (file.startsWith('docs/')) return 'documentation';
  if (file.startsWith('test/') || file.includes('.test.')) return 'fixture or test';
  return file.startsWith('tools/') ? 'tool' : 'consumer';
};
const hitsOf = (text: string, patterns: readonly RegExp[]): readonly Hit[] =>
  text
    .split('\n')
    .flatMap((line, index) =>
      patterns.some((pattern) => pattern.test(line))
        ? [{ line: index + 1, text: line.trim() }]
        : [],
    );
const cell = (text: string): string =>
  text
    .replaceAll('|', String.raw`\|`)
    .replaceAll('`', "'")
    .replaceAll('\n', ' ');

function table(title: string, rows: readonly Row[]): string {
  return `# ${title}\n\nGenerated by npm run rebuild:inventory. All candidates remain adapters until a later PR proves their replacement. Fixture literals are included for review. Line numbers describe the current checkout.\n\n| File and line | Category | Status | Matches | Evidence |\n|---|---|---|---|---|\n${rows
    .map(
      (row) =>
        `| ${row.file}:${String(row.hits[0]?.line ?? 1)} | ${row.category} | ${row.status} | ${String(row.hits.length)} | ${cell(row.hits[0]?.text ?? 'Route or quality gate, included independently of text matches.')} |`,
    )
    .join('\n')}\n`;
}

const files = [
  ...new Set(
    execFileSync(
      'git',
      ['-c', 'core.fsmonitor=false', 'ls-files', '-co', '--exclude-standard', '-z'],
      { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
    )
      .split('\0')
      .filter(Boolean),
  ),
].toSorted((a, b) => a.localeCompare(b));
const consumers: Row[] = [];
const identities: Row[] = [];
const textFiles = files.filter(
  (file) => !file.startsWith('artifacts/') && /\.(?:tsx?|m?[jc]s|json|ya?ml|md|html)$/u.test(file),
);
for (const file of textFiles) {
  const text = await readFile(file, 'utf8');
  const category = categoryOf(file);
  const hits = hitsOf(text, OLD);
  if (hits.length > 0 || QUALITY.has(file) || file.startsWith('src/app/')) {
    consumers.push({ file, category, status: 'adapter', hits });
  }
  if (!/^(?:src|tools|test|eslint)\//u.test(file)) continue;
  for (const [kind, pattern] of [
    ['id construction, parsing or literal', IDS],
    ['Git-host URL construction, parsing or literal', URLS],
  ] as const) {
    const found = hitsOf(text, pattern);
    if (found.length > 0) identities.push({ file, category: kind, status: 'adapter', hits: found });
  }
}
const packageValue: unknown = JSON.parse(await readFile('package.json', 'utf8'));
if (!isRecord(packageValue) || !isRecord(packageValue.scripts)) {
  throw new Error('Package scripts are missing.');
}
const scripts = packageValue.scripts;
for (const [name, command] of Object.entries(scripts)) {
  consumers.push({
    file: `package.json#scripts/${name}`,
    category: 'package script',
    status: 'adapter',
    hits: [{ line: 1, text: String(command) }],
  });
}
await writeSnapshot('artifacts/rebuild', 'consumers.json', consumers);
const outstanding = identitySites();
await writeSnapshot('artifacts/rebuild', 'ids-and-urls-candidates.json', identities);
await writeSnapshot('artifacts/rebuild', 'ids-and-urls.json', outstanding);
const { writeFile } = await import('node:fs/promises');
await writeFile('artifacts/rebuild/consumers.md', table('Model consumer inventory', consumers));
const identityRows = outstanding
  .map((site) => `| ${site.file}:${String(site.line)} | ${cell(site.message)} |`)
  .join('\n');
const identityBody = identityRows === '' ? '' : `${identityRows}\n`;
await writeFile(
  'artifacts/rebuild/ids-and-urls.md',
  `# Uncentralised id and Git-host URL operations\n\n${String(outstanding.length)} runtime operations remain outside src/domain/ids.ts and src/domain/code-links.ts. The enforced architecture inventory checks construction, prefix stripping, child-path parsing and Git-host paths. Literal fixtures, examples, comments and shared-helper references remain in ids-and-urls-candidates.json for inspection; the PR 1 commit preserves the original inventory.\n\n| File and line | Finding |\n|---|---|\n${identityBody}`,
);
await writeExplorerParity();
console.log(
  `${String(consumers.length)} consumer rows; ${String(identities.reduce((sum, row) => sum + row.hits.length, 0))} literal/helper candidates; ${String(outstanding.length)} uncentralised runtime operations. Consumer migration and explorer retirement remain unproven.`,
);

if (outstanding.length > 0) process.exitCode = 1;
