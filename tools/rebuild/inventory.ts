const OLD = [
  /WorkspaceModel|SystemModel|SystemGraph|\bWorkspace\b|\bToday\b|todayData|readToday|readWorkspace|systemModelOf|collectionsOf|onBase|legacyViewOf/u,
  /plan\.generated|domain\/workspace|infrastructure\/(?:today|workspace|plan|service-explorer|explorer)|application\/(?:workspace-model|plan\/derive)/u,
  /knowledge|scan-discovery|scan-interpretation|contracts\.yaml|handlers\.yaml|system\.yaml|story\.yaml|landscape\.yaml|base\.lock|talks_to|scans\/|explorer\//u,
  /\b(?:sys|svc|st|api|msg|sch|if|h):/u,
];
const IDS = [
  /\b(?:sys|svc|app|st|top|ext|lib|dom|api|sub|job|ui|msg|sch|if|h):/u,
  /\b(?:graph|sg|gql|scr|team|actor|area|flow|jny|uj|plan|prog|ev|con|term):/u,
  /(?:split|replace|replaceAll|startsWith|slice|indexOf|includes)\([^\n]*(?:['"`]#|['"`]:)/u,
  /idToToken|tokenToId|ID_PREFIXES|SYSTEM_COLLECTIONS|rootOf|typeOf\(/u,
];
const URLS = [
  /github\\?\.com|gitlab|bitbucket|(?:blob|tree|issues|pull)\//iu,
  /permalink|homeUrlOf|issueUrlOf|parseGitHostUrl|GITHUB_BLOB|\bGITHUB\b|sourceUrl|repoUrl|\$\{host\}/iu,
];
const QUALITY = new Set([
  'test/architecture.test.ts',
  'eslint.config.mjs',
  'knip.json',
  '.jscpd.json',
  'vitest.config.ts',
  'tools/design-drift.baseline.json',
  'tools/page-budget.ts',
]);

interface Hit {
  readonly line: number;
  readonly text: string;
}
interface Row {
  readonly file: string;
  readonly category: string;
  readonly status: 'adapter' | 'migrated' | 'deleted' | 'pending' | 'reference';
  readonly hits: readonly Hit[];
}

const categoryOf = (file: string): string => {
  if (QUALITY.has(file)) return 'quality configuration';
  if (file.startsWith('.agents/')) return 'skill';
  if (file.startsWith('docs/')) return 'documentation';
  if (file.startsWith('test/') || file.includes('.test.')) return 'fixture or test';
  if (file.startsWith('src/app/')) return 'route';
  return file.startsWith('tools/') ? 'tool' : 'consumer';
};
const hitsOf = (text: string, patterns: readonly RegExp[]): readonly Hit[] =>
  text
    .split('\n')
    .flatMap((line, index) =>
      patterns.some((pattern) => pattern.test(line))
        ? [{ line: index + 1, text: line.trim() }]
        : [],
    );
const cell = (text: string): string =>
  text
    .replaceAll('|', String.raw`\|`)
    .replaceAll('`', "'")
    .replaceAll('\n', ' ');

function table(title: string, rows: readonly Row[]): string {
  return `# ${title}\n\nGenerated by npm run rebuild:inventory. Runtime replacements require reviewed current-source proof. The complete original candidate reconciliation and PR9/PR10 work are recorded separately. Line numbers describe the current checkout.\n\n| File and line | Category | Status | Matches | Evidence |\n|---|---|---|---|---|\n${rows
    .map(
      (row) =>
        `| ${row.file}:${String(row.hits[0]?.line ?? 1)} | ${row.category} | ${row.status} | ${String(row.hits.length)} | ${cell(row.hits[0]?.text ?? 'Route or quality gate, included independently of text matches.')} |`,
    )
    .join('\n')}\n`;
}

function identityMatches(file: string, text: string): readonly Row[] {
  if (!/^(?:src|tools|test|eslint)\//u.test(file)) return [];
  return (
    [
      ['id construction, parsing or literal', IDS],
      ['Git-host URL construction, parsing or literal', URLS],
    ] as const
  ).flatMap<Row>(([kind, pattern]) => {
    const hits = hitsOf(text, pattern);
    return hits.length === 0 ? [] : [{ file, category: kind, status: 'adapter', hits }];
  });
}
const files = [
  ...new Set(
    execFileSync(
      'git',
      ['-c', 'core.fsmonitor=false', 'ls-files', '-co', '--exclude-standard', '-z'],
      { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
    )
      .split('\0')
      .filter(Boolean),
  ),
].toSorted((a, b) => a.localeCompare(b));
const candidates: Candidate[] = [];
const sourceFiles = new Map<string, string>();
const identities: Row[] = [];
const textFiles = files.filter(
  (file) => !file.startsWith('artifacts/') && /\.(?:tsx?|m?[jc]s|json|ya?ml|md|html)$/u.test(file),
);
for (const file of textFiles) {
  const text = await readInventorySource(file);
  if (text === null) continue;
  sourceFiles.set(file, text);
  const category = categoryOf(file);
  const hits = hitsOf(text, OLD);
  const nativeUse = usesCanonicalModel(text);
  if (hits.length > 0 || nativeUse || QUALITY.has(file) || file.startsWith('src/app/')) {
    candidates.push({ file, category, hits });
  }
  identities.push(...identityMatches(file, text));
}
const packageValue = modelRecord(JSON.parse(await readFile('package.json', 'utf8')));
const scripts = modelRecord(packageValue?.scripts);
if (scripts === null) {
  throw new Error('Package scripts are missing.');
}
function proofEntry(name: string, command: string): Candidate | null {
  if (!name.startsWith('rebuild:')) return null;
  const file = /tools\/rebuild\/[\w-]+\.ts/u.exec(command)?.[0];
  if (file === undefined || candidates.some((candidate) => candidate.file === file)) return null;
  const source = sourceFiles.get(file);
  if (source === undefined) return null;
  return { file, category: 'tool', hits: hitsOf(source, [/^(?:import|const|if|await)\b/u]) };
}
for (const [name, command] of Object.entries(scripts)) {
  const entry = proofEntry(name, String(command));
  if (entry !== null) candidates.push(entry);
  sourceFiles.set(`package.json#scripts/${name}`, String(command));
  candidates.push({
    file: `package.json#scripts/${name}`,
    category: 'package script',
    hits: [{ line: 1, text: String(command) }],
  });
}
const pr8Review = inventoryReview(
  JSON.parse(await readFile('artifacts/rebuild/pr8/consumer-dispositions.json', 'utf8')),
);
const pr9Review = inventoryReview(
  JSON.parse(await readFile('artifacts/rebuild/pr9/consumer-dispositions.json', 'utf8')),
);
const pr10Review = inventoryReview(
  JSON.parse(await readFile('artifacts/rebuild/pr10/consumer-dispositions.json', 'utf8')),
);
const reviewed = new Map(
  [...pr8Review.dispositions, ...pr9Review.dispositions, ...pr10Review.dispositions].map((row) => [
    row.file,
    row,
  ]),
);
const manifest = { original: pr8Review.original, dispositions: [...reviewed.values()] };
const originalText = await readFile(manifest.original.file, 'utf8');
const original = candidateRows(JSON.parse(originalText));
if (
  sourceHash(originalText) !== manifest.original.sha256 ||
  original.length !== manifest.original.rows
) {
  throw new Error('The frozen original consumer candidates changed.');
}
for (const disposition of manifest.dispositions) {
  for (const reference of [...disposition.evidence, ...disposition.proofs]) {
    if (sourceFiles.has(reference.file)) continue;
    const text = await readFile(reference.file, 'utf8').catch(() => null);
    if (text !== null) sourceFiles.set(reference.file, text);
  }
}
const inventory = consumerInventory(original, candidates, manifest.dispositions, sourceFiles);
const skillUses = skillProducerUses(sourceFiles, scripts);
await writeSnapshot('artifacts/rebuild', 'skill-producers.json', skillUses);
await writeSnapshot('artifacts/rebuild', 'consumer-candidates.json', inventory.candidates);
await writeSnapshot('artifacts/rebuild', 'consumer-pending.json', inventory.pending);
await writeSnapshot('artifacts/rebuild', 'consumer-issues.json', inventory.issues);
await writeSnapshot('artifacts/rebuild', 'consumers.json', inventory.consumers);
await writeFile(
  'artifacts/rebuild/consumers.md',
  table('Runtime model consumers and unresolved candidates', inventory.consumers),
);
await writeSnapshot('artifacts/rebuild', 'consumer-summary.json', {
  originalCandidates: original.length,
  reconciledOriginalCandidates: inventory.candidates.filter((row) => row.original !== null).length,
  freshDiscoveries: inventory.candidates.filter((row) => row.original === null).length,
  candidates: inventory.candidates.length,
  blockingAdapters: inventory.consumers.filter((row) => row.status === 'adapter').length,
  activeLegacyDependencies: inventory.consumers.filter((row) => row.activeLegacyPath.length > 0)
    .length,
  reviewedConsumers: inventory.consumers.filter((row) => row.disposition?.role === 'consumer')
    .length,
  unresolvedRuntimeCandidates: inventory.consumers.filter((row) => row.disposition === undefined)
    .length,
  pendingByStage: {
    pr9: inventory.pending.filter((row) => row.stage === 9).length,
    pr10: inventory.pending.filter((row) => row.stage === 10).length,
  },
  issues: inventory.issues.length,
  skillsInvokingLegacyProducers: skillUses.length,
});
let outstandingCount = 0;
if (!process.argv.includes('--consumers-only')) {
  const outstanding = identitySites();
  outstandingCount = outstanding.length;
  await writeSnapshot('artifacts/rebuild', 'ids-and-urls-candidates.json', identities);
  await writeSnapshot('artifacts/rebuild', 'ids-and-urls.json', outstanding);
  const identityRows = outstanding
    .map((site) => `| ${site.file}:${String(site.line)} | ${cell(site.message)} |`)
    .join('\n');
  const identityBody = identityRows === '' ? '' : `${identityRows}\n`;
  await writeFile(
    'artifacts/rebuild/ids-and-urls.md',
    `# Uncentralised id and Git-host URL operations\n\n${String(outstanding.length)} runtime operations remain outside src/domain/ids.ts and src/domain/code-links.ts. The enforced architecture inventory checks construction, prefix stripping, child-path parsing and Git-host paths. Literal fixtures, examples, comments and shared-helper references remain in ids-and-urls-candidates.json for inspection; the PR 1 commit preserves the original inventory.\n\n| File and line | Finding |\n|---|---|\n${identityBody}`,
  );
  await writeExplorerParity();
}
const adapters = inventory.consumers.filter((row) => row.status === 'adapter');
console.log(
  `${String(original.length)} original candidates; ${String(inventory.candidates.length - original.length)} fresh discoveries; ${String(inventory.consumers.length)} runtime consumer rows (${String(adapters.length)} adapters); ${String(inventory.pending.length)} pending producer/retirement/skill rows; ${String(outstandingCount)} uncentralised runtime id/URL operations.`,
);
for (const issue of inventory.issues) console.error(issue);
const checkSkills = process.argv.includes('--check-skills');
if (checkSkills) {
  for (const use of skillUses) {
    console.error(`${use.file}:${String(use.line)} invokes ${use.target}`);
  }
}
const inventoryBlocked =
  process.argv.includes('--check-consumers') &&
  (adapters.length > 0 || inventory.issues.length > 0);
if (outstandingCount > 0 || (checkSkills && skillUses.length > 0) || inventoryBlocked) {
  process.exitCode = 1;
}
