import type { SemanticOperator } from './scan.generated';

const operators: ReadonlySet<string> = new Set([
  '=',
  ':=',
  '+=',
  '-=',
  '*=',
  '/=',
  '%=',
  '**=',
  '<<=',
  '>>=',
  '>>>=',
  '&=',
  '|=',
  '^=',
  '&^=',
  '&&=',
  '||=',
  '??=',
  '==',
  '!=',
  '===',
  '!==',
  '<',
  '<=',
  '>',
  '>=',
  '+',
  '-',
  '*',
  '/',
  '%',
  '**',
  '<<',
  '>>',
  '>>>',
  '&',
  '|',
  '^',
  '&^',
  '&&',
  '||',
  '??',
  '!',
  '~',
  '++',
  '--',
  '<-',
  'typeof',
  'void',
  'delete',
  'in',
  'instanceof',
  ',',
]);

/** Tokens understood by the supported source languages; other operators stay unknown. */
export function isSemanticOperator(value: string): value is SemanticOperator {
  return operators.has(value);
}
